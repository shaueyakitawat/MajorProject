greeks_new = r'''\subsection{Option Greeks}

To evaluate option sensitivities, the framework utilizes standard analytical Black--Scholes partial derivatives (Greeks) for Delta ($\Delta$), Gamma ($\Gamma$), Vega ($\mathcal{V}$), Theta ($\Theta$), and Rho ($\rho$). The detailed mathematical derivations for these sensitivities are rigorously documented and can be found in Hull (2022) [10]. Within our architecture, these factors are actively computed to penalize the mispricing score according to structural risks.

\subsection{Multi-Timeframe Volatility Fusion}

To reconcile inconsistencies between long-term econometric forecasts and short-term volatility perturbations, we incorporate a weighted fusion mechanism:

\begin{equation}
\sigma_{fusion} = w_{daily}\sigma_{EGARCH} + \sum_{i=1}^{k} w_i \sigma_{RV,i}
\end{equation}

where $\sigma_{RV,i}$ designates the annualized realized volatility calculated spanning the $i$-th intraday scale, and $w$ dictates the respective regime-optimized weights such that $w_{daily} + \sum w_i = 1$.

\subsection{Timeframe Coherence Index (TCI)}

Conflicting trend signals across timeframes significantly escalate the noise ratio; thus, we formulate the Timeframe Coherence Index (TCI) to quantify resolution alignment:

\begin{equation}
TCI = \left| \frac{\sigma_{RV, 5min} - \sigma_{RV, 1hour}}{\sigma_{RV, daily}} \right|^{-1} \times (1 - H)
\end{equation}

where $H$ represents the localized Hurst Exponent. elevated TCI indicates cohesive market dynamics, permitting higher confidence in derived pricing signals.

\subsection{Composite Mispricing M-Score}

Instead of depending on elementary percentage differences, we construct a Composite M-Score that normalizes pure price discontinuities against structural Greek configurations:

\begin{equation}
\label{eq:mscore}
M_{score} = Z \left( \frac{P_{market} - P_{fair}}{\mathcal{V} \times \Gamma} \right) \times \left( \frac{TCI}{1 + |VRP_{dev}|} \right)
\end{equation}

where $Z(\cdot)$ applies the robust Z-score transformation over a moving 30-day epoch, and $VRP_{dev}$ quantifies the current premium deviation from its historical regime baseline. This augmented metric naturally attenuates mispricing illusions driven fundamentally by extreme OTM convexity. High absolute values of $M_{score}$ signify probabilistically robust arbitrage regimes.'''

